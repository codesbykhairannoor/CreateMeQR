const fs = require('fs');
const path = require('path');

const localesDir = path.join(__dirname, 'public', 'locales');
const langs = fs.readdirSync(localesDir);

let updatedCount = 0;

langs.forEach(lang => {
  const transPath = path.join(localesDir, lang, 'translation.json');
  if (fs.existsSync(transPath)) {
    const data = JSON.parse(fs.readFileSync(transPath, 'utf8'));
    
    // Update appTitle if not already updated
    if (data.appTitle && !data.appTitle.includes('CreateMy-QR')) {
      data.appTitle = `${data.appTitle} - CreateMy-QR (No Signup)`;
    }

    // Update tagline if not already updated
    if (data.tagline && !data.tagline.includes('100%')) {
      data.tagline = `${data.tagline}. 100% privacy-safe, client-side generation without signup. Try CreateMy-QR today.`;
    }

    fs.writeFileSync(transPath, JSON.stringify(data, null, 2), 'utf8');
    updatedCount++;
  }
});

console.log(`\u2705 Successfully updated appTitle and tagline in ${updatedCount} languages!`);

// Also update resources.json if it exists (which is generated by generate-i18n.cjs)
const resourcesPath = path.join(__dirname, 'resources.json');
if (fs.existsSync(resourcesPath)) {
  const resources = JSON.parse(fs.readFileSync(resourcesPath, 'utf8'));
  for (const lang in resources) {
    if (resources[lang].translation) {
      const trans = resources[lang].translation;
      if (trans.appTitle && !trans.appTitle.includes('CreateMy-QR')) {
        trans.appTitle = `${trans.appTitle} - CreateMy-QR (No Signup)`;
      }
      if (trans.tagline && !trans.tagline.includes('100%')) {
        trans.tagline = `${trans.tagline}. 100% privacy-safe, client-side generation without signup. Try CreateMy-QR today.`;
      }
    }
  }
  fs.writeFileSync(resourcesPath, JSON.stringify(resources, null, 2), 'utf8');
  console.log(`\u2705 Successfully updated resources.json!`);
}

// Update generate-i18n.cjs to reflect the new English title just in case
const genI18nPath = path.join(__dirname, 'generate-i18n.cjs');
if (fs.existsSync(genI18nPath)) {
  let content = fs.readFileSync(genI18nPath, 'utf8');
  content = content.replace(/"appTitle": "Free QR Code Generator Online"/g, '"appTitle": "Free Custom QR Code Generator Online - CreateMy-QR (No Signup)"');
  content = content.replace(/"tagline": "Create QR Codes with Logo & Color - No Signup, Unlimited"/g, '"tagline": "Create unlimited custom QR codes with logo, color, and dynamic tracking for free. 100% privacy-safe, client-side generation without signup. Try CreateMy-QR today."');
  fs.writeFileSync(genI18nPath, content, 'utf8');
  console.log(`\u2705 Successfully updated generate-i18n.cjs!`);
}
