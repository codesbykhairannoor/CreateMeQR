function slugify(text) {
  return text.toString().toLowerCase()
    .replace(/\s+/g, '-')           // Replace spaces with -
    .replace(/[^\w\-]+/g, '')       // Remove all non-word chars
    .replace(/\-\-+/g, '-')         // Replace multiple - with single -
    .replace(/^-+/, '')             // Trim - from start of text
    .replace(/-+$/, '');            // Trim - from end of text
}

// Improved slugify to support non-latin characters
function robustSlugify(text) {
  // Transliteration for some languages or just use encodeURIComponent for URL safety
  // Since we want readable URLs, we will use a basic replacement and let URL encode handle the rest
  // Alternatively, just replace spaces and lower case it.
  return text.toString().toLowerCase()
    .replace(/\s+/g, '-')
    // Replace multiple dashes
    .replace(/\-\-+/g, '-')
    // Trim dashes
    .replace(/^-+|-+$/g, '');
}

const translateUrl = 'https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=';

async function translateText(text, targetLang) {
  if (targetLang === 'en') return text;
  
  // Prepare english text for translation (remove dashes)
  const plainText = text.replace(/-/g, ' ');

  try {
    const res = await fetch(translateUrl + targetLang + '&dt=t&q=' + encodeURIComponent(plainText));
    const json = await res.json();
    const translated = json[0].map(item => item[0]).join('');
    
    // Slugify the result
    return robustSlugify(translated);
  } catch (err) {
    console.error('Translation error for', targetLang, text);
    return text; // Fallback to english slug
  }
}

async function run() {
  console.log("Generating Localized SEO Slugs for 30 languages...");
  
  const localizedRoutes = {};
  const routeToToolMap = {};
  
  for (const lang of LANGS) {
    localizedRoutes[lang] = {};
    routeToToolMap[lang] = {};
    
    console.log(`Processing [${lang}]...`);
    
    for (const [slug, type] of Object.entries(PSEO_ROUTES)) {
      if (slug === '/') {
        localizedRoutes[lang][type] = '/';
        routeToToolMap[lang]['/'] = type;
        continue;
      }
      
      const cleanSlug = slug.substring(1); // remove leading slash
      const translatedSlug = await translateText(cleanSlug, lang);
      
      // Some languages (like Chinese or Arabic) might produce non-latin characters. 
      // We encode them via encodeURI for valid URL format in modern browsers.
      // But actually, we just store the raw string, the browser will encode it automatically in hrefs.
      // We will ensure it starts with a slash
      const finalSlug = '/' + translatedSlug;
      
      localizedRoutes[lang][type] = finalSlug;
      routeToToolMap[lang][finalSlug] = type;
    }
    
    await new Promise(r => setTimeout(r, 800)); // Rate limit protection
  }
  
  const fileContent = `// Auto-generated by generate-localized-routes.cjs
export const localizedRoutes = ${JSON.stringify(localizedRoutes, null, 2)};
export const routeToToolMap = ${JSON.stringify(routeToToolMap, null, 2)};
`;
  
  fs.writeFileSync(path.join(__dirname, 'src', 'config', 'localizedRoutes.js'), fileContent, 'utf8');
  console.log("Successfully generated src/config/localizedRoutes.js!");
}

run();
