function getLangDict(lang) {
  if (TRANSLATIONS[lang]) {
    return TRANSLATIONS[lang];
  }
  return TRANSLATIONS.en;
}

function updateLocaleFile(filePath, lang) {
  if (!fs.existsSync(filePath)) {
    console.warn(`File not found: ${filePath}`);
    return;
  }

  const content = fs.readFileSync(filePath, 'utf8');
  const json = JSON.parse(content);
  const dict = getLangDict(lang);

  if (dict.appTitle) json.appTitle = dict.appTitle;
  if (dict.tagline) json.tagline = dict.tagline;
  if (dict.badge) json.badge = dict.badge;

  if (json.features) {
    if (dict.signupTitle) json.features.signupTitle = dict.signupTitle;
    if (dict.signupDesc) json.features.signupDesc = dict.signupDesc;
  }

  if (json.home) {
    if (dict.homeSeoDesc) json.home.seoDesc = dict.homeSeoDesc;
    if (dict.homeBadge) json.home.badge = dict.homeBadge;
    if (dict.homeHeroSubtitle) json.home.heroSubtitle = dict.homeHeroSubtitle;
    if (dict.homeWhatIsDesc) json.home.whatIsDesc = dict.homeWhatIsDesc;
    if (dict.homeFaq1a) json.home.faq1a = dict.homeFaq1a;
    if (dict.homeFaq2a) json.home.faq2a = dict.homeFaq2a;
  }

  if (json.static) {
    if (json.static.about && dict.aboutGlobalDesc) {
      json.static.about.globalDesc = dict.aboutGlobalDesc;
    }
    if (json.static.compare) {
      if (dict.compareCost) json.static.compare.cost = dict.compareCost;
      if (dict.compareCost) json.static.compare.tr5val2 = dict.compareCost;
      if (dict.compareTr6val2) json.static.compare.tr6val2 = dict.compareTr6val2;
    }
    if (json.static.pricing) {
      if (dict.pricingSeoTitle) json.static.pricing.seoTitle = dict.pricingSeoTitle;
      if (dict.pricingHeroTitle) json.static.pricing.heroTitle = dict.pricingHeroTitle;
      if (dict.pricingHeroBadge) json.static.pricing.heroBadge = dict.pricingHeroBadge;
      if (dict.pricingSeoDesc) json.static.pricing.seoDesc = dict.pricingSeoDesc;
      if (dict.pricingSeoDesc) json.static.pricing.desc = dict.pricingSeoDesc;
    }
  }

  if (json.rating && dict.ratingSubtitle) {
    json.rating.subtitle = dict.ratingSubtitle;
  }

  if (json.embedModal && dict.embedWhy1) {
    json.embedModal.why1 = dict.embedWhy1;
  }

  if (json.templates && dict.templateHomeSeoDesc) {
    json.templates.homeSeoDesc = dict.templateHomeSeoDesc;
  }

  if (json.geo) {
    if (dict.geoFact) json.geo.fact = dict.geoFact;
    if (dict.geoSoftwareDescription) json.geo.softwareDescription = dict.geoSoftwareDescription;
    if (Array.isArray(json.geo.faqs) && json.geo.faqs.length > 0 && dict.geoFaq0a) {
      json.geo.faqs[0].a = dict.geoFaq0a;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(json, null, 2) + '\n', 'utf8');
  console.log(`Updated: ${filePath} (${lang})`);
}

// 1. Update public/locales for all 30 languages
const localesDir = path.join(__dirname, '..', 'public', 'locales');
const languages = fs.readdirSync(localesDir);

for (const lang of languages) {
  const filePath = path.join(localesDir, lang, 'translation.json');
  updateLocaleFile(filePath, lang);
}

// 2. Also update src/locales/en/translation.json
const srcEnPath = path.join(__dirname, '..', 'src', 'locales', 'en', 'translation.json');
updateLocaleFile(srcEnPath, 'en');

console.log('Successfully synchronized honest, transparent copy across all 30 languages!');
